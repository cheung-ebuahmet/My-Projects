        trad_path = output_path.parent / f"{output_path.stem}_繁體{output_path.suffix}"
        trad_path.write_text(traditional, encoding="utf-8")
        print(f"✅ 简体 → {simp_path.name}（{len(simplified)} 字符）", file=sys.stderr)
        print(f"✅ 繁體 → {trad_path.name}（{len(traditional)} 字符）", file=sys.stderr)
