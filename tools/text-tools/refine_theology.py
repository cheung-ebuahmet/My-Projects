# ─── API 调用 ───────────────────────────────────────────────

def call_deepseek(config, text, system_prompt=SYSTEM_PROMPT):
    """调用 DeepSeek Anthropic 兼容接口"""
    api_key = config["api_key"]
    base_url = config["base_url"]
    model = config["model"]
    messages_url = f"{base_url}/messages"

    # 构建请求载荷（Anthropic Messages 格式）
    payload = json.dumps({
        "model": model,
        "max_tokens": 8192,
        "system": system_prompt,
        "messages": [
            {"role": "user", "content": text}
        ],
    }).encode("utf-8")

    import urllib.request
    import urllib.error

    req = urllib.request.Request(
        messages_url,
        data=payload,
        headers={
            "Content-Type": "application/json",
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=300) as resp:
            result = json.loads(resp.read().decode("utf-8"))
            # 兼容不同响应格式
            if "content" in result:
                return result["content"][0]["text"]
            elif "choices" in result:
                return result["choices"][0]["message"]["content"]
            else:
                print(f"❌ 未知响应格式: {json.dumps(result, ensure_ascii=False)[:200]}", file=sys.stderr)
                sys.exit(1)
    except urllib.error.HTTPError as e:
        error_body = e.read().decode("utf-8")
        print(f"❌ API 调用失败 (HTTP {e.code})", file=sys.stderr)
        print(f"   地址: {messages_url}", file=sys.stderr)
        print(f"   错误: {error_body[:500]}", file=sys.stderr)
        sys.exit(1)
    except urllib.error.URLError as e:
        print(f"❌ 网络错误: {e.reason}", file=sys.stderr)
        print(f"   请检查 API 地址是否可访问: {messages_url}", file=sys.stderr)
        sys.exit(1)


