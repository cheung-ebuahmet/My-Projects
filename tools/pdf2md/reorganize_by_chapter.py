def clean_chapter_text(raw_text: str) -> str:
    """清理章节文本：去页码、去噪声、修复格式"""
    lines = raw_text.split("\n")
    cleaned = []
    for line in lines:
        s = line.strip()
        # 去掉纯页码行
        if re.match(r'^##\s*第\s*\d+\s*页\s*$', s):
            continue
        # 去掉纯数字行
        if re.match(r'^\d+$', s) and len(s) < 10:
            continue
        # 去掉显而易见的单字符/符号噪声
        cn = len(re.findall(r'[一-鿿]', s))
        total = len(s.replace(" ", ""))
        if cn == 0 and len(s) < 8:
            continue
        if total == 0:
            continue
        if cn > 0 and cn / max(total, 1) < 0.05 and len(s) > 15:
            continue
        cleaned.append(s)

    text = "\n".join(cleaned)
    # 修复引用所多余的空白
    text = re.sub(r'([一-鿿])\s+([一-鿿])', r'\1\2', text)
    text = re.sub(r'\s+([，。！？、；：」」】])', r'\1', text)
    text = re.sub(r'[，,]{2,}', '，', text)
    # 去掉多余行距
    text = re.sub(r'\n{4,}', '\n\n\n', text)

    return text


def detect_chapter_boundaries(pages_text: str) -> list:
    """
    检测章节边界
    策略：前10页用精确页码映射，之后用关键词匹配 + 剩余内容合并
    """
    page_markers = list(re.finditer(r'(## 第 (\d+) 页)', pages_text))
    num_pages = len(page_markers)

    # 精确页码映射（已知的可靠章节）
    PAGE_CHAPTER_MAP = {
        1: {"id": "cover", "title": "封面与版权页"},
        2: {"id": "cover", "title": "封面与版权页"},
        3: {"id": "foreword", "title": "题记"},
        4: {"id": "foreword", "title": "题记"},
        5: {"id": "toc", "title": "目录"},
        6: {"id": "ch01_preface", "title": "中国回教小史·题记"},
        7: {"id": "ch01_01", "title": "第一章 中国大食间的交通"},
        8: {"id": "ch01_01", "title": "第一章 中国大食间的交通"},
        9: {"id": "ch01_01", "title": "第一章 中国大食间的交通"},
        10: {"id": "ch01_01", "title": "第一章 中国大食间的交通"},
    }

    # 找第一次出现的页码索引
    page_num_to_idx = {}
    for idx, m in enumerate(page_markers):
        pn = int(m.group(2))
        if pn not in page_num_to_idx:
            page_num_to_idx[pn] = idx

    boundaries = []

    # 已处理的页码
    processed_pages = set()

    # 先处理前10页的精确映射
    for pn in sorted(PAGE_CHAPTER_MAP.keys()):
        if pn in page_num_to_idx and pn <= num_pages:
            idx = page_num_to_idx[pn]
            ch_info = PAGE_CHAPTER_MAP[pn]

            # 检查这个章节是否已添加
            existing = [b for b in boundaries if b["id"] == ch_info["id"]]
            if existing:
                existing[0]["end_page_idx"] = max(existing[0]["end_page_idx"], idx + 1)
            else:
                boundaries.append({
                    "id": ch_info["id"],
                    "title": ch_info["title"],
                    "start_page_idx": idx,
                    "end_page_idx": idx + 1,
                })
            processed_pages.add(idx)

    # 剩余页面按关键词检测章节
    remaining_starts = [i for i in range(num_pages) if i not in processed_pages]

    if remaining_starts:
        # 按顺序检测剩余页的关键词
        # 先全部提取文本
        page_texts = []
        for idx in remaining_starts:
            start = page_markers[idx].end()
            end = page_markers[idx + 1].start() if idx + 1 < num_pages else len(pages_text)
            page_texts.append(pages_text[start:end].strip())

        combined = "\n".join(page_texts)

        # 检测后续章节关键词
        chapter_order = [ch for ch in CHAPTERS if ch["id"] not in
                         {"cover", "foreword", "toc", "ch01_preface", "ch01_01"}]

        ch_found = []
        for ch in chapter_order:
            for kw in ch["keywords"]:
                if kw in combined:
                    ch_found.append(ch)
                    break

        if ch_found:
            # 计算每个章节的粗略位置比例
            for ch in ch_found:
                # 找第一个关键字的位置
                first_kw = None
                for kw in ch["keywords"]:
                    pos = combined.find(kw)
                    if pos >= 0:
                        if first_kw is None or pos < first_kw:
                            first_kw = pos
                if first_kw is not None:
                    # 按比例映射到页面索引
                    ratio = first_kw / max(len(combined), 1)
                    mapped_idx = remaining_starts[int(ratio * len(remaining_starts))]
                    mapped_idx = min(mapped_idx, remaining_starts[-1])

                    boundaries.append({
                        "id": ch["id"],
                        "title": ch["title"],
                        "start_page_idx": mapped_idx,
                        "end_page_idx": mapped_idx + 5,  # 估计5页
                    })

        # 最后，把没有匹配到章节的剩余页全部合并到最后一个块
        if ch_found:
            # 确保最后一个章节覆盖到末尾
            if boundaries:
                boundaries[-1]["end_page_idx"] = max(boundaries[-1]["end_page_idx"], num_pages)
        else:
            # 没有检测到任何章节，将所有剩余页作为"正文"合并
            boundaries.append({
                "id": "body",
                "title": "正文",
                "start_page_idx": remaining_starts[0],
                "end_page_idx": num_pages,
            })

    # 按起始页排序
    boundaries.sort(key=lambda b: b["start_page_idx"])

    return boundaries


def extract_chapter_content(pages_text: str, start_page_idx: int, end_page_idx: int) -> str:
    """从页标记文本中提取指定范围的页面内容，去掉页眉标记"""
    page_markers = list(re.finditer(r'(## 第 \d+ 页)', pages_text))
    parts = []

    for idx in range(start_page_idx, min(end_page_idx, len(page_markers))):
        start = page_markers[idx].end()
        if idx + 1 < len(page_markers):
            end = page_markers[idx + 1].start()
        else:
            end = len(pages_text)
        content = pages_text[start:end].strip()
        if content:
            parts.append(content)

    return "\n".join(parts)


def reorganize_markdown(input_path: str, output_path: str):
    """主函数：按章节重组"""
    print(f"\n{'='*60}")
    print(f"📚 按章节重组: {Path(input_path).name}")
    print(f"{'='*60}")

    with open(input_path, "r", encoding="utf-8") as f:
        content = f.read()

    # 分离 frontmatter
    frontmatter = ""
    body = content
    if content.startswith("---"):
        parts = content.split("---", 2)
        if len(parts) >= 3:
            frontmatter = "---" + parts[1] + "---"
            body = parts[2]

    # 检测章节边界
    boundaries = detect_chapter_boundaries(body)
    print(f"📖 检测到 {len(boundaries)} 个章节:")

    # 构建章节内容
    chapter_outputs = []

    for b in boundaries:
        ch_id = b["id"]
        ch_title = b["title"]

        # 检查是否有参考文本
        ref = REFERENCE_TEXTS.get(ch_id)

        if ref:
            content_text = ref
            source = "参考文本"
        else:
            # 提取 OCR 内容并清理
            raw = extract_chapter_content(body, b["start_page_idx"], b["end_page_idx"])
            content_text = clean_chapter_text(apply_fixes(raw))
            source = "OCR识别"

        chapter_outputs.append({
            "id": ch_id,
            "title": ch_title,
            "content": content_text,
            "source": source,
        })

        line_preview = content_text[:60].replace("\n", " ").strip()
        print(f"   {ch_title} ({source}) — {line_preview}...")

    # 组织输出
    output_lines = [
        frontmatter,
        "",
        "# 中国伊斯兰史存稿",
        "",
        "> 白寿彝 著 | 宁夏人民出版社 1983年",
        "> 由扫描版 PDF 识别整理，按章节结构编排",
        "",
        "---",
        "",
        "## 目 次",
        "",
    ]

    for ch in chapter_outputs:
        output_lines.append(f"- [{ch['title']}](#{ch['id']})")

    output_lines += ["", "---", ""]

    for ch in chapter_outputs:
        output_lines.append(f"## {ch['title']}")
        output_lines.append("")
        output_lines.append(ch["content"])
        output_lines.append("")
        output_lines.append("---")
        output_lines.append("")

    output = "\n".join(output_lines)

    # 写入
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(output)

    # 统计
    cn_chars = len(re.findall(r'[一-鿿]', output))
    with_ref = sum(1 for ch in chapter_outputs if ch["source"] == "参考文本")
    with_ocr = sum(1 for ch in chapter_outputs if ch["source"] == "OCR识别")

    print(f"\n{'='*60}")
    print(f"✅ 完成！")
    print(f"   文件: {output_path}")
    print(f"   中文字符: {cn_chars:,}")
    print(f"   章节: {len(chapter_outputs)}（参考文本 {with_ref} 章 + OCR修复 {with_ocr} 章）")
    print(f"{'='*60}\n")

    return output_path


