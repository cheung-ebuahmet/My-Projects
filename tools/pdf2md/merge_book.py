def apply_fixes(text):
    for w, c in FIXES.items():
        if w and w in text:
            text = text.replace(w, c)
    return text


def clean_text(text):
    """综合清理"""
    # 去页码
    text = re.sub(r'## 第 \d+ 页\n?', '', text)
    # 去目次
    text = re.sub(r'## 目 次\n[\s\S]*?\n---\n', '', text)
    text = re.sub(r'^## 目 次$', '', text, flags=re.MULTILINE)
    # 去封面噪声
    text = re.sub(r'犒.*?犒', '', text)
    text = re.sub(r'[xaXA#@\$%\^&*_]{4,}', '', text)
    # 中文间空格
    text = re.sub(r'([一-鿿])\s+([一-鿿])', r'\1\2', text)
    text = re.sub(r'\s+([，。！？、；：）」」】])', r'\1', text)
    # 连续标点
    text = re.sub(r'[，,]{2,}', '，', text)
    text = re.sub(r'[。.]{2,}', '。', text)
    text = re.sub(r'\n{4,}', '\n\n\n', text)
    # 引号修复
    text = text.replace('「', '"').replace('」', '"')
    return text.strip()


def normalize_title(t):
    """规范化章节标题"""
    t = t.strip().replace("## ", "")
    # 精确匹配
    if t in TITLE_ALIASES:
        return TITLE_ALIASES[t]
    # 模糊匹配
    for alias, canonical in TITLE_ALIASES.items():
        if alias in t or t in alias:
            return canonical
        if SM(None, t[:6], alias[:6]).ratio() > 0.6:
            return canonical
    # 包含匹配
    for alias, canonical in sorted(TITLE_ALIASES.items(), key=lambda x: -len(x[0])):
        if alias[:4] in t or t[:4] in alias:
            return canonical
    return t


